export function translate(language, key, values = {}) {
  const message = messages[language]?.[key] ?? messages.ko[key];
  if (message === undefined) throw new Error(`Unknown UI message: ${key}`);
  return message.replace(/\{([a-zA-Z]+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function initialLanguage(search) {
  return new URLSearchParams(search).get('lang') === 'en' ? 'en' : 'ko';
}
